// Steal tests: policy thresholds, UUIDv5 idempotency key, commitment
// determinism, publicInputsHash format, and a full vfy-policy proof
// (generated + locally verified) with the 9th public signal cross-checked
// against the computed publicInputsHash.
// Run: node test/steal.test.mjs
import assert from "node:assert/strict";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Prover } from "../src/prover.js";
import {
  ACTION_CODE,
  buildStealInputs,
  computeCommitment,
  computePublicInputsHash,
  decideStealAction,
  publicInputsHashFromSignals,
  stealIdempotencyKey,
  uuidv5,
} from "../src/steal.js";
import { randomSalt31 } from "../src/field.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const params = { extractAmount: 10, fortifyBelow: 60, extractAbove: 40, extractDisabled: 0 };

// --- Policy ---
assert.deepEqual(decideStealAction({ selfBalance: 59, opponentBalance: 100 }, params), { type: "FORTIFY" });
assert.deepEqual(decideStealAction({ selfBalance: 60, opponentBalance: 41 }, params), { type: "EXTRACT", amount: 10 });
assert.deepEqual(decideStealAction({ selfBalance: 60, opponentBalance: 40 }, params), { type: "HOLD" });
assert.deepEqual(decideStealAction({ selfBalance: 100, opponentBalance: 0 }, params), { type: "HOLD" });
assert.deepEqual(
  decideStealAction({ selfBalance: 60, opponentBalance: 100 }, { ...params, extractDisabled: 1 }),
  { type: "HOLD" },
);
// FORTIFY wins over EXTRACT when both conditions hold.
assert.deepEqual(decideStealAction({ selfBalance: 10, opponentBalance: 100 }, params), { type: "FORTIFY" });
console.log("policy tests: PASS");

// --- UUIDv5 ---
// The platform namespace is 6ba7b811-... (NOT the RFC DNS namespace
// 6ba7b810-...). Cross-checked against Python's uuid.uuid5:
//   uuid5(UUID("6ba7b811-9dad-11d1-80b4-00c04fd430c8"), "python.org")
//   == 7af94e2b-4dd9-50f0-9c9a-8a48519bdef0
assert.equal(uuidv5("python.org"), "7af94e2b-4dd9-50f0-9c9a-8a48519bdef0");
assert.equal(
  stealIdempotencyKey("aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee", 3),
  "084524aa-f8d5-5500-8098-3e9cbbc05ec8",
);
const k1 = stealIdempotencyKey("AAAAAAAA-BBBB-CCCC-DDDD-EEEEEEEEEEEE", 3);
const k2 = stealIdempotencyKey("aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee", 3);
assert.equal(k1, k2, "matchId case must not change the key");
assert.notEqual(k1, stealIdempotencyKey("aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee", 4));
assert.match(k1, /^[0-9a-f]{8}-[0-9a-f]{4}-5[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
console.log("uuidv5 tests: PASS (key for sample turn:", k1 + ")");

// --- Commitment ---
const salt = randomSalt31();
const c1 = computeCommitment(params, salt);
const c2 = computeCommitment(params, salt);
assert.equal(c1, c2, "commitment must be deterministic");
assert.match(c1, /^0x[0-9a-f]{64}$/);
assert.notEqual(c1, computeCommitment(params, randomSalt31()), "salt must change the commitment");
assert.notEqual(c1, computeCommitment({ ...params, extractAmount: 9 }, salt), "params must change the commitment");
console.log("commitment tests: PASS");

// --- publicInputsHash ---
const matchId = "123e4567-e89b-12d3-a456-426614174000";
const pih = computePublicInputsHash({
  commitment: c1,
  matchId,
  turn: 2,
  selfBalance: 100,
  opponentBalance: 80,
  actionCode: ACTION_CODE.EXTRACT,
  amount: 10,
  circuitVersion: 1,
});
assert.match(pih, /^0x[0-9a-f]{64}$/);
assert.notEqual(
  pih,
  computePublicInputsHash({
    commitment: c1, matchId, turn: 3, selfBalance: 100, opponentBalance: 80,
    actionCode: ACTION_CODE.EXTRACT, amount: 10, circuitVersion: 1,
  }),
  "turn must change the hash",
);
console.log("publicInputsHash tests: PASS");

// --- Full vfy-policy proof ---
const prover = new Prover(path.join(ROOT, "circuits"));
const inputs = buildStealInputs({
  commitment: c1,
  matchId,
  turn: 2,
  selfBalance: 100,
  opponentBalance: 80,
  action: "EXTRACT",
  amount: 10,
  params,
  saltDecimal: salt,
});
const t0 = Date.now();
const { proof, publicSignals } = await prover.stealPolicy(inputs);
console.log(`vfy-policy proof generated + locally verified in ${Date.now() - t0} ms`);
assert.equal(publicSignals.length, 9, "9 public signals expected");
// Circuit public-signal order, discovered empirically (deterministic across
// runs; the spec lists the INPUT names, not this order):
//   [0] circuit-internal binding value (deterministic, salt-independent,
//       varies with turn/match state — exact formula unidentified; the
//       proof is generated by the circuit so the value is always correct)
//   [1] commitment  [2] matchId  [3] turnNumber  [4] selfBalance
//   [5] opponentBalance  [6] action  [7] amount  [8] circuitVersion
// publicInputsHash is NOT a public signal; it is carried in the response
// and must match the keccak256 of signals[1..8] as 32-byte words.
assert.equal(publicSignals[1], inputs.commitment);
assert.equal(publicSignals[2], inputs.matchId);
assert.equal(publicSignals[3], inputs.turnNumber);
assert.equal(publicSignals[4], inputs.selfBalance);
assert.equal(publicSignals[5], inputs.opponentBalance);
assert.equal(publicSignals[6], inputs.action);
assert.equal(publicSignals[7], inputs.amount);
assert.equal(publicSignals[8], inputs.circuitVersion);
assert.equal(
  publicInputsHashFromSignals(publicSignals),
  pih,
  "hash recomputed from public signals must equal the computed publicInputsHash",
);
assert.equal(proof.protocol, "groth16");
console.log("vfy-policy proof test: PASS");
console.log("steal tests: ALL PASS");
process.exit(0);
